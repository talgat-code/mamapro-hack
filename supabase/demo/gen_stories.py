METRICS = ["new_word", "tantrum", "bad_sleep", "bad_eat", "homework"]


def lerp(a, b, x):
    return a + (b - a) * x


def poisson(lam):
    # простая выборка Пуассона (малые λ)
    import math
    L, k, p = math.exp(-lam), 0, 1.0
    while True:
        p *= rnd.random()
        if p <= L:
            return k
        k += 1


def weeks_for(st):
    start = dt.date.fromisoformat(st["start"])
    out = []
    n = st["weeks"]
    for w in range(n):
        x = w / max(1, n - 1)
        x = x ** 0.85  # быстрее в начале, плато к концу — как обычно и бывает
        days = 7 if rnd.random() > 0.15 else rnd.choice([5, 6])  # иногда пропуски записей
        g0, g1 = st["trend"]["good"]
        share = min(0.95, max(0.05, lerp(g0, g1, x) + rnd.uniform(-0.1, 0.1)))
        good = round(days * share)
        bad = max(0, round((days - good) * rnd.uniform(0.25, 0.55)))
        normal = days - good - bad
        wk = {"start": (start + dt.timedelta(days=7 * w)).isoformat(), "good": good, "normal": normal, "bad": bad}
        for m in METRICS:
            if m in st["trend"]:
                a, b = st["trend"][m]
                lam = max(0.0, lerp(a, b, x))
                wk[m] = min(days if m != "new_word" else 12, max(0, round(lam + rnd.uniform(-0.9, 0.9))))
            else:
                wk[m] = 0
        out.append(wk)
    return out


